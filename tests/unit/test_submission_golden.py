"""Golden-file test: every writer emits byte-identical XML to the original filings-cvm.

``tests/golden/submission_xml.json.gz`` was generated by running the ORIGINAL filings-cvm
writers (``origin/main`` at ``f915150``) over every document its own test suite builds. Each
case stores the validated input as JSON, the exact XML string and the sha256 of the file the
writer wrote to disk. A moved or refactored writer must reproduce both.
"""

import gzip
import hashlib
import importlib
import json
from pathlib import Path

import pytest

import layouts_cvm


_PATH_GOLDEN = Path(__file__).parent.parent / "golden" / "submission_xml.json.gz"
_LIST_CASES = json.loads(gzip.decompress(_PATH_GOLDEN.read_bytes()))["cases"]
_LIST_IDS = [f"{dict_case['writer']}-{int_idx}" for int_idx, dict_case in enumerate(_LIST_CASES)]


def _load_doc(dict_case: dict) -> object:
    """Rebuild the validated document of a golden case from its JSON.

    Parameters
    ----------
    dict_case : dict
        One entry of the golden file.

    Returns
    -------
    object
        The validated schema document.
    """
    mod_schema = importlib.import_module(
        f"layouts_cvm._internal.config.schemas.{dict_case['doc_module']}"
    )
    return getattr(mod_schema, dict_case["doc_class"]).model_validate_json(dict_case["doc_json"])


def _export(dict_case: dict, output_path: str | None) -> str | None:
    """Run the case's writer on its document.

    Parameters
    ----------
    dict_case : dict
        One entry of the golden file.
    output_path : str or None
        Destination file, or None to get the XML string.

    Returns
    -------
    str or None
        The XML string when ``output_path`` is None.
    """
    cls_writer = getattr(layouts_cvm, dict_case["writer"])()
    return cls_writer.export(_load_doc(dict_case), output_path, **dict_case["kwargs"])


@pytest.mark.parametrize("dict_case", _LIST_CASES, ids=_LIST_IDS)
def test_plain_data_input_matches_the_original(dict_case: dict) -> None:
    """A plain mapping is validated by the writer and yields the same XML as the model."""
    cls_writer = getattr(layouts_cvm, dict_case["writer"])()

    str_xml = cls_writer.export(json.loads(dict_case["doc_json"]), None, **dict_case["kwargs"])

    assert str_xml == dict_case["xml"]


@pytest.mark.parametrize("dict_case", _LIST_CASES, ids=_LIST_IDS)
def test_xml_string_matches_the_original(dict_case: dict) -> None:
    """The returned XML string equals the original writer's, character for character."""
    assert _export(dict_case, None) == dict_case["xml"]


@pytest.mark.parametrize("dict_case", _LIST_CASES, ids=_LIST_IDS)
def test_written_file_matches_the_original(dict_case: dict, tmp_path: Path) -> None:
    """The file written to disk has the same bytes (sha256) as the original writer's."""
    path_out = tmp_path / "out.xml"

    _export(dict_case, str(path_out))

    assert hashlib.sha256(path_out.read_bytes()).hexdigest() == dict_case["file_sha256"]


def test_every_writer_has_a_golden_case() -> None:
    """All 14 writers are pinned by at least one golden case."""
    set_writers = {dict_case["writer"] for dict_case in _LIST_CASES}

    assert len(set_writers) == 14
